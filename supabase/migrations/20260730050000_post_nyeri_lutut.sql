## Urutan yang saya sarankan

1. **Berhenti dulu, atau kurangi jauh.** Mengayuh menembus nyeri lutut jarang berakhir baik.
2. **Periksa apa yang baru berubah.** Sepatu baru, cleat baru, sadel baru, atau lonjakan jarak tempuh. Penyebabnya sering ada di situ.
3. **Rekam dan ukur.** Satu klip dari samping, lihat sudut lututnya.
4. **Ubah satu hal, lima milimeter,** catat angka awalnya, lalu uji beberapa kali jalan.
5. **Kalau tidak membaik dalam satu atau dua minggu, berhenti menebak.** Temui fisioterapis atau bike fitter. Nyeri yang bertahan sambil Anda terus menggeser sadel adalah nyeri yang sedang Anda biarkan.

