## FAQ

### Kenapa lutut saya sakit saat bersepeda?

Paling sering karena posisi sadel dan pola beban latihan. Nyeri di depan lutut umumnya dikaitkan dengan sadel yang terlalu rendah atau terlalu maju; nyeri di belakang lutut dengan sadel yang terlalu tinggi atau terlalu mundur. Nyeri yang menetap perlu diperiksa tenaga medis.

### Nyeri depan lutut sepeda biasanya karena apa?

Sadel terlalu rendah adalah tersangka pertama, diikuti sadel terlalu maju dan kebiasaan mengayuh dengan gir berat pada kadens rendah.

### Apakah boleh tetap bersepeda kalau lutut nyeri?

Kalau nyerinya ringan dan hilang saat istirahat, kurangi intensitas dan periksa posisinya. Kalau nyerinya menetap, memburuk, atau disertai bengkak, berhenti dan temui dokter atau fisioterapis.

### Berapa lama sampai perubahan posisi terasa hasilnya?

Umumnya beberapa kali jalan. Hari pertama setelah menyetel selalu terasa aneh, jadi menilai dari satu sesi biasanya menyesatkan.

### Apakah kadens berpengaruh ke nyeri lutut?

Sangat. Mengayuh gir berat pada kadens rendah memindahkan beban ke sendi. Menaikkan kadens ke sekitar 80–90 rpm sering meringankan sebelum penyetelan apa pun dilakukan.

### Apakah alat ini bisa mendiagnosis penyebab nyeri saya?

Tidak. Alat ini mengukur sudut tubuh Anda dari satu sisi dan membandingkannya dengan rentang yang dipakai di bike fitting. Ia tidak melihat sendi Anda, tidak tahu riwayat cedera Anda, dan bukan alat medis.

