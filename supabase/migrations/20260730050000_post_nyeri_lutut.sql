## Kenapa letak nyerinya penting

Lutut Anda menekuk dan lurus sekitar lima ribu kali per jam bersepeda. Gerakan itu berulang, terkendali, dan sangat konsisten — yang berarti kesalahan kecil terjadi lima ribu kali juga, selalu di sudut yang sama.

Karena itu, di mana rasa sakitnya muncul cenderung menunjuk ke arah tertentu. Ini bukan diagnosis, dan bukan aturan pasti. Ini pola yang cukup sering muncul sehingga layak dicek lebih dulu sebelum Anda mengubah hal lain secara acak.

## Nyeri di depan lutut

Di sekitar atau di bawah tempurung lutut. Ini yang paling umum di antara pesepeda.

Yang biasanya dikaitkan dengannya:

- **Sadel terlalu rendah.** Lutut menekuk terlalu dalam di puncak kayuhan, dan beban di bagian depan lutut naik. Ini penyebab yang paling sering.
- **Sadel terlalu maju.** Efeknya mirip: lutut berada terlalu jauh di depan poros pedal.
- **Gir terlalu berat, kadens terlalu rendah.** Mengayuh 60 rpm dengan gir besar memindahkan beban ke sendi alih-alih ke sistem kardio. Menaikkan kadens ke 80–90 sering menolong lebih cepat daripada menyetel apa pun.
- **Beban latihan naik terlalu cepat.** Jarak tempuh yang melonjak dalam waktu singkat adalah penyebab yang sama seringnya dengan posisi, dan tidak bisa diperbaiki dengan kunci L.

Cek pertama: rekam diri Anda dari samping dan lihat sudut lutut di titik terbawah kayuhan. Kalau lebih dari 40°, sadel Anda kemungkinan terlalu rendah. Cara mengukurnya ada di [Tinggi Sadel Sepeda yang Benar](/blog/tinggi-sadel-sepeda-yang-benar).

## Nyeri di belakang lutut

Di lipatan belakang, kadang terasa menjalar ke hamstring.

Yang biasanya dikaitkan dengannya:

- **Sadel terlalu tinggi.** Kaki meraih pedal di titik terbawah dan bagian belakang lutut tertarik berulang kali.
- **Sadel terlalu mundur.** Efeknya menyerupai sadel terlalu tinggi.
- **Pergelangan kaki menjinjit** di bawah kayuhan untuk mencapai pedal — sering merupakan gejala dari dua hal di atas.

Cek dari video: sudut lutut di titik terbawah di bawah sekitar 28° mendukung dugaan ini. Jangan menilai dari goyangan panggul — pesepeda dengan sadel yang sudah benar pun menunjukkan sekitar 7° gerakan panggul, jadi goyangan halus adalah hal normal, bukan gejala.³ Turunkan sadel lima milimeter, jangan lebih, lalu uji beberapa kali jalan.

## Nyeri di sisi luar lutut

Sering dikaitkan dengan iritasi iliotibial band. Yang biasanya dilihat lebih dulu:

- **Posisi cleat** — terutama sudut rotasinya, yang memaksa kaki menghadap ke arah yang tidak alami bagi Anda.
- **Float cleat terlalu sempit**, sehingga kaki tidak punya kebebasan sedikit pun untuk berputar.
- **Jarak antar-pedal (Q-factor)** yang tidak cocok dengan lebar panggul Anda.
- Sadel terlalu tinggi, lagi.

Ini yang paling sulit diperbaiki sendiri dari video samping, karena penyebabnya sering berada di bidang yang tidak terlihat kamera dari sisi. Kalau nyeri sisi luar menetap, ini kasus di mana fitter profesional benar-benar sepadan.

## Nyeri di sisi dalam lutut

Biasanya dikaitkan dengan posisi cleat yang menempatkan kaki terlalu ke luar, atau jarak antar-pedal yang terlalu lebar untuk Anda.

