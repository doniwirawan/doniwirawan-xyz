Ini juga bagian dari bike fit yang paling sering diabaikan, padahal ia berada di titik di mana seluruh tenaga Anda masuk ke sepeda.

## Kenapa ini penting lebih dari yang terlihat

Kaki Anda terkunci ke pedal. Kalau posisi kunci itu memaksa kaki menghadap ke arah yang tidak alami bagi Anda, lutut tidak punya pilihan selain ikut berputar — lima ribu kali per jam.

Karena itu, keluhan yang muncul dari cleat sering terasa di lutut, bukan di kaki. Orang lalu menghabiskan berminggu-minggu menyetel sadel untuk masalah yang sebenarnya berada dua puluh sentimeter di bawahnya.

## Sumbu 1: maju-mundur

Ini yang paling berpengaruh, dan yang paling banyak dibicarakan.

Titik awal klasik: **tulang di pangkal jempol kaki (metatarsal pertama) tepat di atas poros pedal.** Cara mengeceknya sederhana — raba tonjolan tulang itu dari luar sepatu, tandai dengan spidol di sisi sepatu, pasang cleat, lalu lihat dari samping apakah tanda itu segaris dengan poros pedal.

Menggeser cleat **ke belakang** (kaki lebih maju di atas pedal) mengurangi beban pada betis dan tendon Achilles, dan banyak pesepeda jarak jauh menyukainya. Menggeser **ke depan** memberi rasa lebih responsif untuk sprint. Sebagian besar orang berada baik-baik saja di antara keduanya.

Satu hal yang perlu diingat: **menggeser cleat ke belakang secara efektif menurunkan tinggi sadel Anda**, karena jarak dari tulang duduk ke titik tumpu berubah. Kalau Anda menggeser cleat lebih dari beberapa milimeter, ukur ulang sudut lutut Anda.

## Sumbu 2: rotasi

Ini yang paling sering salah, dan yang paling langsung terhubung ke nyeri lutut.

Aturannya: **cleat harus mengikuti arah kaki Anda secara alami, bukan memaksa kaki lurus ke depan.** Sebagian orang berjalan dengan ujung kaki mengarah sedikit keluar, sebagian sedikit ke dalam. Keduanya normal, dan keduanya harus dihormati oleh cleat.

Cara sederhana mengeceknya: duduk di tepi meja dengan kaki menggantung bebas dan santai, lalu lihat ke arah mana ujung kaki Anda menghadap dengan sendirinya. Itu sudut yang sebaiknya diikuti.

Perhatikan juga **float** — kebebasan berputar yang diizinkan cleat sebelum terlepas. Cleat float nol memaksa kaki pada satu sudut mati dan hanya masuk akal kalau sudutnya benar-benar tepat. Untuk kebanyakan orang, cleat dengan float beberapa derajat jauh lebih aman bagi lutut.

## Sumbu 3: kiri-kanan

Sumbu yang hampir tidak pernah disentuh siapa pun.

Menggeser cleat ke arah dalam sepatu membuat kaki Anda duduk lebih jauh dari sepeda; menggeser ke luar membuatnya lebih dekat. Jarak total antara kedua kaki ini disebut **Q-factor**, dan idealnya sesuai dengan lebar panggul Anda.

Panduan kasarnya: kalau lutut Anda cenderung mengarah ke dalam saat mengayuh, coba geser cleat agar kaki menjauh dari sepeda; kalau mengarah ke luar, sebaliknya. Kalau kebutuhannya besar, ada pedal dengan poros lebih panjang dan spacer khusus.

## Cara menyetel tanpa merusak apa pun

1. **Tandai posisi lama sebelum melepas apa pun.** Gambar garis di sol sepatu mengelilingi cleat dengan spidol. Ini jaring pengaman Anda.
2. **Ubah satu sumbu sekali, dan sedikit.** Dua milimeter untuk maju-mundur, satu atau dua derajat untuk rotasi. Cleat sangat sensitif — perubahan yang di tangan terasa sepele bisa terasa besar di lutut setelah satu jam.
3. **Uji di jalan yang aman dan pendek dulu.** Jangan jadikan perjalanan seratus kilometer sebagai uji coba cleat baru.
4. **Kencangkan sesuai spesifikasi.** Baut cleat yang longgar akan berputar sendiri saat mengayuh, dan Anda akan mengejar masalah yang bergerak.
5. **Ukur ulang sudut lutut** kalau Anda menggeser maju-mundur lebih dari beberapa milimeter, atau mengganti sepatu.

