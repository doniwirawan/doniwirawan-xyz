## FAQ

### Di mana posisi cleat yang benar?

Titik awal yang umum: tulang di pangkal jempol kaki berada tepat di atas atau sedikit di belakang poros pedal, dengan sudut cleat mengikuti arah kaki Anda secara alami.

### Apakah cleat mempengaruhi nyeri lutut?

Sangat. Rotasi cleat yang memaksa kaki menghadap arah yang tidak alami adalah penyebab umum nyeri di sisi luar dan sisi dalam lutut.

### Float itu apa dan berapa yang sebaiknya dipakai?

Float adalah kebebasan berputar yang diizinkan cleat sebelum terlepas. Untuk kebanyakan orang, cleat dengan float beberapa derajat lebih aman bagi lutut daripada float nol.

### Apakah menggeser cleat mengubah tinggi sadel?

Secara efektif ya. Menggeser cleat ke belakang mengubah jarak dari tulang duduk ke titik tumpu, jadi ukur ulang sudut lutut Anda setelah perubahan yang lebih dari beberapa milimeter.

### Berapa banyak yang aman diubah sekali setel?

Dua milimeter untuk maju-mundur, satu sampai dua derajat untuk rotasi. Tandai posisi lama dengan spidol sebelum melepas cleat.

### Apakah posisi cleat bisa dicek dari video?

Tidak dari video samping. Rotasi dan jarak kiri-kanan berada di bidang yang tidak terlihat dari arah itu, dan penilaian 2D dari depan pun terlalu kasar untuk penyetelan halus.

