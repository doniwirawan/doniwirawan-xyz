## What I Learned

The most expensive part of the build wasn't the frame. It was the groupset.

* Groupset: approximately 51% of the bike's value
* Frame: approximately 23%
* Wheelset: approximately 6%
* Cockpit and finishing kit: the remainder

Building the bike myself also changed how I think about maintenance. Instead of paying a shop for every adjustment, I invested in tools that will last for years.

Looking back, I don't just own a gravel bike. I now understand how every part works, how to service it, and how to build another one in the future. That knowledge is worth just as much as the bike itself.$body$,
