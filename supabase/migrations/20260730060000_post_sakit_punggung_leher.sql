## Tiga sudut yang menunjukkannya

Kalau sadel sudah benar tetapi punggung dan leher tetap sakit, tiga angka ini yang perlu dilihat. Ini yang diukur [Bike Fit Analyzer](https://bikefit.doniwirawan.xyz) dari klip Anda, dengan rentang untuk posisi road:

- **Sudut badan dari horizontal — target 40°–50°.** Di bawah 40° berarti Anda sangat membungkuk. Itu aerodinamis, dan mahal harganya kalau punggung Anda belum siap.
- **Sudut siku — target 15°–30°.** Siku yang terkunci lurus artinya Anda sedang meraih. Semua getaran jalan naik langsung lewat lengan ke bahu dan leher, tanpa peredam.
- **Sudut bahu — target 80°–95°.** Hubungan antara badan dan lengan. Kalau ini yang paling meleset sementara dua lainnya wajar, biasanya panjang stem yang jadi soal.

Dua catatan sebelum Anda membandingkan angka Anda dengan angka orang lain. **Target sudut badan berbeda menurut jenis sepeda** — road endurance, road race, gravel, MTB, dan TT punya rentang sendiri, jadi 44° yang hijau di sepeda endurance bukan angka yang sama artinya di sepeda TT. Dan rentang di atas **diukur dinamis**, sambil orangnya mengayuh; panduan yang mengutip angka statis akan terlihat beberapa derajat lebih kecil untuk posisi yang sebenarnya sama.¹ ²

Rekam dari samping, kayuh santai 20–30 detik, tangan di posisi yang biasa Anda pakai sepanjang klip. Panduan merekamnya ada di [tulisan pengantar](/blog/bike-fitting-cek-sendiri-dari-video). Videonya diproses di browser Anda dan tidak diunggah ke mana pun.

## Tanda jangkauan Anda terlalu jauh

- **Siku terkunci lurus** hampir sepanjang waktu.
- **Leher mendongak berlebihan** untuk bisa melihat ke depan — ini sumber sakit leher yang paling langsung.
- **Anda menggeser duduk ke ujung depan sadel** tanpa sadar, karena posisi itu memperpendek jangkauan.
- **Bahu terasa tegang** setelah setengah jam, bukan setelah dua jam.
- **Punggung bawah terasa panas atau ngilu** di jalan datar yang panjang.
- **Tangan menahan beban berat**, bukan sekadar memegang.

## Yang murah dulu, sebelum beli apa pun

Urutan ini dari yang gratis ke yang mahal. Kerjakan satu per satu, dan uji beberapa kali jalan di antaranya.

1. **Posisi sadel dulu, selalu.** Sadel yang terlalu mundur menambah jangkauan Anda tanpa Anda menyentuh setang. Selesaikan bagian belakang sebelum menyentuh bagian depan.
2. **Naikkan setang.** Pindahkan spacer dari atas ke bawah stem, atau balik stem menghadap ke atas. Ini gratis, butuh sepuluh menit, dan efeknya paling besar dibanding usahanya.
3. **Putar sudut setang.** Beberapa derajat pada drop bar mengubah posisi hood, dan hood adalah tempat tangan Anda sembilan puluh persen waktu.
4. **Geser posisi hood** pada setang. Sering kali beberapa milimeter sudah cukup.
5. **Baru ganti stem.** Lebih pendek 10 mm adalah perubahan yang terasa jelas. Ini yang termurah di antara komponen yang perlu dibeli, dan hampir selalu lebih tepat daripada mengganti sadel atau setang.

Ganti frame adalah jawaban terakhir, bukan pertama. Frame yang terlalu besar memang tidak bisa diperbaiki sepenuhnya, tapi jauh lebih banyak orang membeli frame baru karena stem-nya salah.

## Bagian yang bukan salah sepeda

Ini bagian yang tidak enak didengar, dan saya menulisnya karena dulu berlaku untuk saya.

Posisi membungkuk di sepeda ditopang oleh perut, punggung bawah, dan pinggul — bukan oleh tangan. Kalau otot-otot itu belum kuat, tubuh akan menumpukan beban ke lengan dan leher, dan leher akan mengeluh. Sepeda yang disetel sempurna pun tidak bisa menggantikan bagian ini.

Selain itu, fleksibilitas hamstring dan pinggul menentukan seberapa membungkuk yang masuk akal untuk Anda hari ini. Posisi pro punya sudut badan yang sangat rendah karena mereka melatihnya bertahun-tahun. Menyalin posisi itu tanpa menyalin tahun-tahunnya adalah cara yang cepat untuk menyakiti punggung sendiri.

Naikkan setang sekarang, dan turunkan lagi pelan-pelan kalau memang badan Anda menyusul. Itu urutan yang benar.

## Tangan kebas: perlakukan berbeda

Kalau tangan atau jari Anda kebas atau kesemutan saat bersepeda, jangan tempatkan itu di kategori yang sama dengan pegal. Kebas menandakan tekanan pada saraf, dan mengabaikannya berminggu-minggu bukan ide yang baik.

Yang bisa dicoba: kurangi beban di tangan dengan mengurangi jangkauan, ubah sudut pergelangan tangan, pakai bar tape yang lebih tebal atau sarung tangan berbantalan, dan sering ganti posisi tangan. Kalau kebasnya tetap muncul setelah itu, atau bertahan setelah Anda turun dari sepeda, temui dokter.

## Kalau sakitnya menetap

Tulisan ini soal penyetelan sepeda, bukan diagnosis. Nyeri punggung yang menetap, menjalar ke kaki, atau disertai kebas perlu diperiksa langsung oleh fisioterapis atau dokter — bukan diselesaikan dengan menggeser spacer.

