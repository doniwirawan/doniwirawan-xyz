## FAQ

### Kenapa punggung saya sakit saat bersepeda?

Paling sering karena jangkauan ke setang terlalu jauh atau terlalu rendah, sehingga punggung bawah bekerja terlalu keras untuk menahan posisi. Penyebab kedua yang sama seringnya adalah kekuatan badan yang belum menopang posisi tersebut.

### Kenapa leher saya sakit setelah bersepeda?

Biasanya karena Anda harus mendongak berlebihan untuk melihat ke depan — akibat posisi setang yang terlalu rendah atau terlalu jauh. Siku yang terkunci lurus memperburuknya karena getaran jalan naik langsung ke bahu dan leher.

### Apa yang sebaiknya disetel lebih dulu?

Posisi sadel, selalu. Sadel yang terlalu mundur menambah jangkauan tanpa Anda menyentuh bagian depan sepeda. Setelah itu naikkan setang, baru pertimbangkan stem yang lebih pendek.

### Apakah perlu ganti stem atau ganti sepeda?

Stem lebih dulu, hampir selalu. Stem 10 mm lebih pendek adalah perubahan yang jelas terasa dan jauh lebih murah. Ganti frame adalah jawaban terakhir.

### Berapa sudut badan yang wajar saat bersepeda road?

Rentang yang dipakai alat ini adalah 40°–50° dari garis horizontal untuk posisi road. Lebih rendah dari itu masuk akal hanya kalau fleksibilitas dan kekuatan badan Anda mendukungnya.

### Tangan saya kebas saat bersepeda, apakah normal?

Tidak. Kebas menandakan tekanan pada saraf. Kurangi beban di tangan dan sering ganti posisi pegangan, dan kalau tetap muncul atau bertahan setelah turun dari sepeda, periksakan ke dokter.

